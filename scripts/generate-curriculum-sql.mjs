#!/usr/bin/env node
// Generates the curriculum seed SQL from lib/curriculum.ts.
//
//   node scripts/generate-curriculum-sql.mjs            # print seed SQL
//   node scripts/generate-curriculum-sql.mjs --check F  # exit 1 if F's seed block is out of date
//
// The seed is wrapped in "-- BEGIN CURRICULUM SEED" / "-- END CURRICULUM SEED"
// markers inside a migration file. After editing lib/curriculum.ts, copy the
// output into a new migration so the database matches the app.
import { readFileSync } from "node:fs";
import { BOARDS, SUBJECTS, OFFERINGS } from "../lib/curriculum.ts";

const q = (v) => (v === null || v === undefined ? "NULL" : `'${String(v).replace(/'/g, "''")}'`);

function seedSql() {
  const lines = [];
  lines.push("-- BEGIN CURRICULUM SEED (generated by scripts/generate-curriculum-sql.mjs; do not edit by hand)");

  lines.push("INSERT INTO public.curriculum_boards (code, name, short_name, family, sort_order) VALUES");
  lines.push(BOARDS.map((b, i) => `  (${q(b.code)}, ${q(b.name)}, ${q(b.shortName)}, ${q(b.family)}, ${i})`).join(",\n"));
  lines.push("ON CONFLICT (code) DO UPDATE SET name = EXCLUDED.name, short_name = EXCLUDED.short_name, family = EXCLUDED.family, sort_order = EXCLUDED.sort_order;");
  lines.push("");

  lines.push("INSERT INTO public.curriculum_subjects (code, name) VALUES");
  lines.push(Object.entries(SUBJECTS).map(([code, name]) => `  (${q(code)}, ${q(name)})`).join(",\n"));
  lines.push("ON CONFLICT (code) DO UPDATE SET name = EXCLUDED.name;");
  lines.push("");

  lines.push("INSERT INTO public.curriculum_offerings (board, stage, label, note, sort_order) VALUES");
  lines.push(OFFERINGS.map((o, i) => `  (${q(o.board)}, ${q(o.stage)}, ${q(o.label)}, ${q(o.note ?? null)}, ${i})`).join(",\n"));
  lines.push("ON CONFLICT (board, stage) DO UPDATE SET label = EXCLUDED.label, note = EXCLUDED.note, sort_order = EXCLUDED.sort_order;");
  lines.push("");

  const groups = OFFERINGS.flatMap((o) => o.groups.map((g, i) => ({ o, g, i })));
  lines.push("INSERT INTO public.curriculum_groups (board, stage, code, name, electives_required, note, sort_order) VALUES");
  lines.push(groups.map(({ o, g, i }) => `  (${q(o.board)}, ${q(o.stage)}, ${q(g.code)}, ${q(g.name)}, ${g.electivesRequired ?? 0}, ${q(g.note ?? null)}, ${i})`).join(",\n"));
  lines.push("ON CONFLICT (board, stage, code) DO UPDATE SET name = EXCLUDED.name, electives_required = EXCLUDED.electives_required, note = EXCLUDED.note, sort_order = EXCLUDED.sort_order;");
  lines.push("");

  // Group subjects are replaced wholesale so removed subjects disappear too.
  // One compact row per group (compulsory / core / elective arrays), expanded in SQL.
  const arr = (codes) => (codes.length ? `ARRAY[${codes.map(q).join(", ")}]` : "ARRAY[]::text[]");
  const rows = [];
  for (const o of OFFERINGS) {
    for (const g of o.groups) {
      const seen = new Set();
      const uniq = (codes) => codes.filter((c) => !seen.has(c) && seen.add(c));
      const compulsory = uniq(o.compulsory);
      const core = uniq(g.core);
      const electives = uniq(g.electives ?? []);
      rows.push(`  (${q(o.board)}, ${q(o.stage)}, ${q(g.code)}, ${arr(compulsory)}, ${arr(core)}, ${arr(electives)})`);
    }
  }
  lines.push("DELETE FROM public.curriculum_group_subjects;");
  lines.push("INSERT INTO public.curriculum_group_subjects (board, stage, group_code, subject_code, kind, sort_order)");
  lines.push("SELECT g.board, g.stage, g.group_code, s.code, s.kind,");
  lines.push("       (row_number() OVER (PARTITION BY g.board, g.stage, g.group_code ORDER BY s.kind_order, s.ord))::int - 1");
  lines.push("FROM (VALUES");
  lines.push(rows.join(",\n"));
  lines.push(") AS g(board, stage, group_code, compulsory, core, electives)");
  lines.push("CROSS JOIN LATERAL (");
  lines.push("  SELECT c, 'compulsory', 1, o FROM unnest(g.compulsory) WITH ORDINALITY AS t(c, o)");
  lines.push("  UNION ALL SELECT c, 'core', 2, o FROM unnest(g.core) WITH ORDINALITY AS t(c, o)");
  lines.push("  UNION ALL SELECT c, 'elective', 3, o FROM unnest(g.electives) WITH ORDINALITY AS t(c, o)");
  lines.push(") AS s(code, kind, kind_order, ord);");
  lines.push("-- END CURRICULUM SEED");
  return lines.join("\n");
}

const args = process.argv.slice(2);
if (args[0] === "--check") {
  const file = readFileSync(args[1], "utf8");
  const match = file.match(/-- BEGIN CURRICULUM SEED[\s\S]*?-- END CURRICULUM SEED/);
  if (!match || match[0] !== seedSql()) {
    console.error(`Curriculum seed in ${args[1]} is out of date with lib/curriculum.ts`);
    process.exit(1);
  }
  console.log("Curriculum seed is up to date.");
} else {
  process.stdout.write(seedSql() + "\n");
}
